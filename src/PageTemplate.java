import java.io.BufferedReader;
import java.io.File;
import java.io.FileReader;
import java.io.IOException;

/**
 * PART B (Step 3) - TEMPLATE INJECTION
 * Wraps the compiled body in a full HTML skeleton.
 * If the user keeps a "template.html" in the source folder we load that,
 * otherwise we fall back to the built-in skeleton (with inline CSS).
 * Placeholders: {{TITLE}}, {{HEADER}}, {{BODY}}
 */
public class PageTemplate {

    private static final String DEFAULT_SKELETON =
        "<!DOCTYPE html>\n" +
        "<html lang=\"en\">\n" +
        "<head>\n" +
        "  <meta charset=\"UTF-8\">\n" +
        "  <title>{{TITLE}}</title>\n" +
        "  <style>\n" +
        "    body   { font-family: Arial, sans-serif; max-width: 800px; margin: 40px auto;\n" +
        "             padding: 0 20px; line-height: 1.6; color: #333; background: #fafafa; }\n" +
        "    header { background: #2c3e50; color: white; padding: 15px 25px; border-radius: 6px; }\n" +
        "    h1     { color: #2c3e50; border-bottom: 2px solid #2c3e50; padding-bottom: 5px; }\n" +
        "    h2     { color: #2980b9; }\n" +
        "    strong { color: #c0392b; }\n" +
        "    footer { margin-top: 40px; font-size: 12px; color: #888; text-align: center; }\n" +
        "  </style>\n" +
        "</head>\n" +
        "<body>\n" +
        "  <header>{{HEADER}}</header>\n" +
        "  <main>\n" +
        "{{BODY}}" +
        "  </main>\n" +
        "  <footer>Generated by Java Static Site Generator</footer>\n" +
        "</body>\n" +
        "</html>\n";

    private String skeleton = DEFAULT_SKELETON;

    // Try to read a custom layout; if anything goes wrong just keep the default.
    public void loadCustomLayout(File templateFile) {
        if (!templateFile.exists() || !templateFile.isFile()) {
            return;
        }
        StringBuilder text = new StringBuilder();
        try (BufferedReader reader = new BufferedReader(new FileReader(templateFile))) {
            String line;
            while ((line = reader.readLine()) != null) {
                text.append(line).append("\n");
            }
            skeleton = text.toString();
            System.out.println("Using custom layout: " + templateFile.getName());
        } catch (IOException e) {
            System.out.println("Could not read template.html, using default layout.");
        }
    }

    // Plug the document's pieces into the skeleton.
    public String apply(HTMLDocument doc) {
        return skeleton.replace("{{TITLE}}", doc.getTitle())
                       .replace("{{HEADER}}", doc.getHeader())
                       .replace("{{BODY}}", doc.getBody());
    }
}
